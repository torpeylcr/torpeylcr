export const getFertilizerById = (id) => nzFertilizers.find((f) => f.id === id)

export const fertilizersByType = nzFertilizers.reduce((acc, f) => {
  if (!acc[f.type]) acc[f.type] = []
  acc[f.type].push(f)
  return acc
}, {})

export const fertilizersByNutrient = (nutrient) =>
  nzFertilizers.filter((f) => f.targetNutrientDeficiency.includes(nutrient))
